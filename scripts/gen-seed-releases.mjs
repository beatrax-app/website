// Regenerates the committed release seed from the GitHub Releases API.
//
// The changelog page reads live releases at build time; the seed is what it
// falls back to when the API is unreachable or rate-limited. Run this after a
// release so the fallback does not go stale:
//
//   node scripts/gen-seed-releases.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const SOURCE = process.argv[2] ?? "nightworksio/beatrax";
const ORG = "beatrax-app";

const raw = JSON.parse(
  execFileSync("gh", ["api", `repos/${SOURCE}/releases?per_page=20`], { encoding: "utf8" }),
);

// Links point at the destination org rather than wherever the API was read
// from, so the seed stays correct once the repository has moved.
const retarget = (url) => url.replace(/github\.com\/[^/]+\/beatrax/, `github.com/${ORG}/beatrax`);

const releases = raw
  .filter((r) => !r.prerelease && r.published_at)
  .sort((a, b) => b.published_at.localeCompare(a.published_at))
  .map((r) => ({
    repo: "beatrax",
    tag: r.tag_name,
    name: r.name || r.tag_name,
    url: retarget(r.html_url),
    publishedAt: r.published_at,
    body: r.body || undefined,
    assets: (r.assets ?? []).map((a) => ({
      name: a.name,
      url: retarget(a.browser_download_url),
      size: a.size,
    })),
  }));

const header = `// Generated by scripts/gen-seed-releases.mjs — do not edit by hand.
//
// The fallback for the changelog and download pages when the Releases API is
// unreachable at build time. Release bodies are authored by the release
// pipeline, not here. Assets carry no platform: the motor derives it from the
// filename so live and seeded releases are classified by the same rule.

export interface SeedRelease {
  repo: string;
  tag: string;
  name: string;
  url: string;
  publishedAt: string;
  body?: string;
  assets: { name: string; url: string; size: number }[];
}

export const seedReleasesRaw: SeedRelease[] = `;

writeFileSync("src/data/seed-releases.ts", header + JSON.stringify(releases, null, 2) + ";\n");
console.log(`wrote ${releases.length} releases`);
